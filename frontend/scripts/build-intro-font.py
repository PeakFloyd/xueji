"""Build the intro's font assets from Noto Sans SC (variable, wght 100-900).

1. Subsets the variable font to exactly the characters used by the intro
   (all non-ASCII chars found in src/components/intro + printable ASCII),
   keeping the weight axis, and writes src/components/intro/assets/intro-sans.woff2.
2. Instantiates the font at wght=900 and flattens the outlines of the glyphs
   used by the type -> icon morph into polygons: src/components/intro/engine/glyphs.ts.

Usage (from frontend/):  python scripts/build-intro-font.py
The source font is downloaded to scripts/.cache/ on first run.
"""

from __future__ import annotations

import io
import json
import pathlib
import urllib.request

from fontTools.pens.basePen import BasePen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "scripts" / ".cache"
SRC_URL = "https://github.com/google/fonts/raw/main/ofl/notosanssc/NotoSansSC%5Bwght%5D.ttf"
SRC_FONT = CACHE / "NotoSansSC-VF.ttf"
INTRO_DIR = ROOT / "src" / "components" / "intro"
OUT_FONT = INTRO_DIR / "assets" / "intro-sans.woff2"
OUT_GLYPHS = INTRO_DIR / "engine" / "glyphs.ts"
MORPH_GLYPHS = "ID"


def ensure_source() -> None:
    if SRC_FONT.exists():
        return
    CACHE.mkdir(parents=True, exist_ok=True)
    print(f"downloading {SRC_URL}")
    with urllib.request.urlopen(SRC_URL) as r:
        SRC_FONT.write_bytes(r.read())


def collect_text() -> str:
    chars = {chr(c) for c in range(0x20, 0x7F)}
    for path in INTRO_DIR.rglob("*"):
        if path.suffix in {".ts", ".tsx"} and path.name != "glyphs.ts":
            chars.update(ch for ch in path.read_text(encoding="utf-8") if ord(ch) > 0x7E)
    return "".join(sorted(chars))


def subset_font(text: str) -> None:
    font = TTFont(SRC_FONT)
    opts = Options(flavor="woff2", layout_features=["*"], name_IDs=["*"], notdef_outline=True)
    sub = Subsetter(options=opts)
    sub.populate(text=text)
    sub.subset(font)
    OUT_FONT.parent.mkdir(parents=True, exist_ok=True)
    font.flavor = "woff2"
    font.save(OUT_FONT)
    print(f"wrote {OUT_FONT.relative_to(ROOT)}  ({OUT_FONT.stat().st_size / 1024:.1f} KB, {len(text)} chars)")


class FlattenPen(BasePen):
    """Flattens outlines into closed polygons (font units, y flipped to screen space)."""

    STEPS = 14

    def __init__(self, glyphset):
        super().__init__(glyphset)
        self.contours: list[list[tuple[float, float]]] = []
        self.cur: list[tuple[float, float]] = []

    def _pt(self, p):
        return (round(p[0], 2), round(-p[1], 2))

    def _moveTo(self, pt):
        self.cur = [self._pt(pt)]

    def _lineTo(self, pt):
        self.cur.append(self._pt(pt))

    def _curveToOne(self, pt1, pt2, pt3):
        p0, p1, p2, p3 = self._getCurrentPoint() or (0.0, 0.0), pt1, pt2, pt3
        for i in range(1, self.STEPS + 1):
            t = i / self.STEPS
            mt = 1 - t
            x = mt**3 * p0[0] + 3 * mt * mt * t * p1[0] + 3 * mt * t * t * p2[0] + t**3 * p3[0]
            y = mt**3 * p0[1] + 3 * mt * mt * t * p1[1] + 3 * mt * t * t * p2[1] + t**3 * p3[1]
            self.cur.append(self._pt((x, y)))

    def _qCurveToOne(self, pt1, pt2):
        p0, p1, p2 = self._getCurrentPoint() or (0.0, 0.0), pt1, pt2
        for i in range(1, self.STEPS + 1):
            t = i / self.STEPS
            mt = 1 - t
            x = mt * mt * p0[0] + 2 * mt * t * p1[0] + t * t * p2[0]
            y = mt * mt * p0[1] + 2 * mt * t * p1[1] + t * t * p2[1]
            self.cur.append(self._pt((x, y)))

    def _closePath(self):
        if len(self.cur) > 1 and self.cur[0] == self.cur[-1]:
            self.cur.pop()
        self.contours.append(self.cur)
        self.cur = []

    _endPath = _closePath


def signed_area(poly):
    return sum(a[0] * b[1] - b[0] * a[1] for a, b in zip(poly, poly[1:] + poly[:1])) / 2


def extract_glyphs() -> None:
    font = TTFont(SRC_FONT)
    sub = Subsetter(options=Options(layout_features=[]))
    sub.populate(text=MORPH_GLYPHS)
    sub.subset(font)
    inst = instancer.instantiateVariableFont(font, {"wght": 900})
    buf = io.BytesIO()
    inst.save(buf)
    buf.seek(0)
    inst = TTFont(buf)
    cmap = inst.getBestCmap()
    gs = inst.getGlyphSet()
    out = {}
    for ch in MORPH_GLYPHS:
        name = cmap[ord(ch)]
        pen = FlattenPen(gs)
        gs[name].draw(pen)
        contours = sorted(pen.contours, key=lambda c: -abs(signed_area(c)))
        out[ch] = {"advance": gs[name].width, "contours": contours}
    body = json.dumps(out, separators=(",", ":"))
    OUT_GLYPHS.write_text(
        "// Generated by scripts/build-intro-font.py - do not edit.\n"
        "// Noto Sans SC @ wght 900, font units (upm 1000), y-down, contours sorted outer-first.\n"
        "export type GlyphOutline = { advance: number; contours: [number, number][][] };\n"
        f"export const GLYPHS: Record<string, GlyphOutline> = {body};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT_GLYPHS.relative_to(ROOT)}")


if __name__ == "__main__":
    ensure_source()
    subset_font(collect_text())
    extract_glyphs()
